export const rentOpsRecordChanges = pgTable("rent_ops_record_changes", {
  id: id("id").primaryKey(),
  entityType: varchar("entity_type", { length: 80 }).notNull(),
  targetId: id("target_id").notNull(),
  revision: integer("revision").notNull(),
  origin: varchar("origin", { length: 20 }).notNull(),
  actorSubject: varchar("actor_subject", { length: 160 }),
  occurredAt: timestamp("occurred_at", { withTimezone: true }).notNull(),
  changedFields: text("changed_fields").array().notNull(),
}, (table) => ({
  entityTypeValid: check("rent_ops_record_changes_entity_type_check", sql`${table.entityType} IN ('property','unit','person','household_membership','tenancy','lease_term','security_deposit','subsidy_contract','application','document','activity','recurring_schedule')`),
  revisionPositive: check("rent_ops_record_changes_revision_positive", sql`${table.revision} > 1`),
  adminActorRequired: check("rent_ops_record_changes_admin_actor_check", sql`${table.origin} <> 'admin' OR ${table.actorSubject} IS NOT NULL`),
  targetRevisionUnique: uniqueIndex("rent_ops_record_changes_target_revision_unique").on(table.entityType, table.targetId, table.revision),
  targetIndex: index("rent_ops_record_changes_target_index").on(table.entityType, table.targetId, table.occurredAt),
}));

/**
 * Restricted, lossless RM source archive. This table is intentionally omitted
 * from `rentOpsTables`, so the normal repository and every browser snapshot
 * have no code path to select raw tenant/application payloads.
 */
export const rentOpsSourcePayloads = pgTable("rent_ops_source_payloads", {
  id: id("id").primaryKey(),
  system: text("system").notNull(),
  sourceCollection: text("source_collection").notNull(),
  sourceId: text("source_id").notNull(),
  sourceUpdatedAt: timestamp("source_updated_at", { withTimezone: true }),
  payload: jsonb("payload").$type<Record<string, unknown>>().notNull(),
  checksumSha256: varchar("checksum_sha256", { length: 64 }).notNull(),
  importRunId: id("import_run_id").notNull().references(() => rentOpsImportRuns.id),
  importedAt: timestamp("imported_at", { withTimezone: true }).defaultNow().notNull(),
}, (table) => ({
  versionUnique: uniqueIndex("rent_ops_source_payloads_version_unique").on(table.system, table.sourceCollection, table.sourceId, table.checksumSha256),
  importRunIndex: index("rent_ops_source_payloads_import_run_index").on(table.importRunId),
}));

