/**
 * PostgreSQL tables for the bounded Rent Operations module. The module keeps
 * posted financial facts append-only at the service boundary; the table
 * definitions intentionally expose reversal links instead of delete helpers.
 * Amounts are integer cents to avoid decimal arithmetic in the domain/API.
 */

const id = (name: string) => varchar(name, { length: 160 });
const money = (name: string) => integer(name);
const metadata = () => jsonb("metadata").$type<Record<string, unknown>>();

export const rentOpsSchemaMeta = pgTable("rent_ops_schema_meta", {
  version: integer("version").primaryKey(),
  checksumSha256: varchar("checksum_sha256", { length: 64 }),
  appliedAt: timestamp("applied_at", { withTimezone: true }).defaultNow().notNull(),
});

/** Immutable ordered migration ledger. v1's legacy meta row remains intact;
 * this additive ledger records every applied version and exact source digest. */
export const rentOpsSchemaMigrations = pgTable("rent_ops_schema_migrations", {
  version: integer("version").primaryKey(),
  checksumSha256: varchar("checksum_sha256", { length: 64 }).notNull(),
  appliedAt: timestamp("applied_at", { withTimezone: true }).defaultNow().notNull(),
  downSqlSha256: varchar("down_sql_sha256", { length: 64 }),
});

